const fmt = new Intl.DateTimeFormat('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' })
export const formatStoryDate = (iso) => fmt.format(new Date(`${iso}T00:00:00Z`))

// A story photo with a small (800px) and full-size source.
export function storyImg(s, sizes = '(max-width: 860px) 100vw, 33vw') {
  const base = '/assets/img/stories/'
  // Small copies are 800px wide (Paise's original is only 480px, so it has no larger copy).
  if (s.img === 'firsts-with-paise.jpg') return `<img src="${base}${s.img}" alt="${s.alt}" loading="lazy" />`
  return `<img src="${base}sm/${s.img}" srcset="${base}sm/${s.img} 800w, ${base}${s.img} 1800w" sizes="${sizes}" alt="${s.alt}" loading="lazy" />`
}

export function storyCard(s, { lead = false } = {}) {
  return `
    <article class="story${lead ? ' story--lead' : ''}">
      <a href="${s.url}">
        <div class="story__img">${storyImg(s, lead ? '(max-width: 860px) 100vw, 56vw' : '(max-width: 860px) 40vw, 14vw')}</div>
        <div>
          <time datetime="${s.date}">${formatStoryDate(s.date)}</time>
          <h3>${s.title}</h3>
          ${lead ? `<p>${s.excerpt}</p>` : ''}
        </div>
      </a>
    </article>`
}
